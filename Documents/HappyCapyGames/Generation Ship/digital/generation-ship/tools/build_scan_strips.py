"""Builds the Scan Tableau strip atlases: for every card code, the strip of the card that stays visible in a
tableau next to its scan dial (name banner + colour orb on techs/expeditions; the lower part of a sector below
the techs that overlap it), cut from the game's card art at a low resolution, one atlas per language.
TableauReader compares each read dial's photo strip against these to catch misreads and phantom reads, and to
let weak readings in when the strip confirms them.

    python tools/build_scan_strips.py      -> assets/scan/strips/<LANG>.png + scripts/photo_scan/strip_layout.gd
(the layout is a GDScript constant, not a JSON file: exports only include *.csv/*.webm/*.mp4 data files)

Re-run after card art changes (assets/cards). Box/resolution must match tableau_reader.gd (STRIP_*).
"""
import csv, os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, "data", "Generation Ship Full Card Details - %s.csv")
CARDS = os.path.join(ROOT, "assets", "cards")
OUT = os.path.join(ROOT, "assets", "scan", "strips")
PPM = 1.5                                   # STRIP_PPM in tableau_reader.gd
SIZE_MM = {"sector": (67.0, 44.0), "tech": (44.0, 67.0), "expedition": (44.0, 67.0)}
# STRIP_BOX in tableau_reader.gd (card mm: x, y, w, h)
BOX = {"tech": (1.0, 52.0, 43.0, 14.5), "expedition": (1.0, 53.0, 43.0, 13.5), "sector": (1.0, 21.0, 65.0, 22.0)}
COLS = 16


def rows(sheet):
    with open(DATA % sheet, encoding="utf-8") as fh:
        yield from csv.DictReader(fh)


def cards():
    """(code, deck, folder, file name) for every card with a scan code."""
    out = []
    for sheet, deck, folder in (("Techs", "tech", "Tech"), ("Promos", "tech", "Promo"), ("Expeditions", "expedition", "Expedition"),
                                ("Advanced Sectors", "sector", "Sector"), ("Dust Sectors", "sector", "Sector")):
        for r in rows(sheet):
            try:
                code = int(r.get("Code") or "")
            except ValueError:
                continue
            link = (r.get("Link") or "").strip()
            if code > 0 and link and code not in [c[0] for c in out]:
                out.append((code, deck, folder, link))
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    cs = cards()
    cell = {d: (round(BOX[d][2] * PPM), round(BOX[d][3] * PPM)) for d in BOX}
    # layout: portrait strips (techs, promos, expeditions) in rows of COLS, then sector strips
    layout = {}
    x = y = 0; row_h = 0; col = 0; last_deck = None
    for code, deck, folder, link in sorted(cs, key=lambda c: (c[1] == "sector", c[0])):
        w, h = cell[deck]
        if (deck == "sector") != (last_deck == "sector") and last_deck is not None or col == COLS:
            x = 0; y += row_h; row_h = 0; col = 0
        layout[code] = [x, y, w, h, deck]
        x += w; col += 1; row_h = max(row_h, h); last_deck = deck
    W = max(v[0] + v[2] for v in layout.values()); H = max(v[1] + v[3] for v in layout.values())
    langs = sorted(os.listdir(os.path.join(CARDS, "Tech")))
    for lang in langs:
        atlas = Image.new("RGB", (W, H), (0, 0, 0))
        missing = 0
        for code, deck, folder, link in cs:
            p = os.path.join(CARDS, folder, lang, link)
            if not os.path.exists(p):
                p = os.path.join(CARDS, folder, "EN", link)
            if not os.path.exists(p):
                missing += 1; continue
            im = Image.open(p).convert("RGB")
            ppm = im.width / SIZE_MM[deck][0]
            bx, by, bw, bh = BOX[deck]
            crop = im.crop((round(bx * ppm), round(by * ppm), round((bx + bw) * ppm), round((by + bh) * ppm)))
            x0, y0, w, h, _ = layout[code]
            atlas.paste(crop.resize((w, h), Image.LANCZOS), (x0, y0))
        atlas.save(os.path.join(OUT, lang + ".png"), optimize=True)
        print(lang, f"{W}x{H}", "missing", missing)
    lines = ["extends RefCounted", "# Generated by tools/build_scan_strips.py - do not edit. Where each card's strip sits in",
             "# assets/scan/strips/<LANG>.png: code -> [x, y, w, h, deck]; strips cut from STRIP_BOX at PPM.", "",
             f"const PPM: float = {PPM}", "const CELLS: Dictionary = {"]
    for c in sorted(layout):
        x, y, w, h, deck = layout[c]
        lines.append(f'\t{c}: [{x}, {y}, {w}, {h}, "{deck}"],')
    lines.append("}")
    with open(os.path.join(ROOT, "scripts", "photo_scan", "strip_layout.gd"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
